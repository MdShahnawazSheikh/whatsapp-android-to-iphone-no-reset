#!/bin/bash
# Fix-up pass after watoi. Makes the imported rows look like rows WhatsApp iOS writes itself:
#  - sets lastMessage/lastMessageDate on every new chat (watoi never does; without it chats can be invisible)
#  - session type 1 for groups, flags 256, read status, message flags, sentDate
#  - marks current group participants active, carries starred flags
# usage: post.sh <ChatStorage.sqlite> <msgstore_shim.db> <baseline_session_pk> <baseline_message_pk> <baseline_member_pk>
set -euo pipefail
DB="$1"; SHIM="$2"; S="$3"; M="$4"; G="$5"
sqlite3 "$DB" <<SQL
ATTACH '$SHIM' AS a;
BEGIN;
UPDATE ZWACHATSESSION SET ZSESSIONTYPE=1, ZSPOTLIGHTSTATUS=1  WHERE Z_PK>$S AND ZGROUPINFO IS NOT NULL;
UPDATE ZWACHATSESSION SET ZSESSIONTYPE=0, ZSPOTLIGHTSTATUS=-5 WHERE Z_PK>$S AND ZGROUPINFO IS NULL;
UPDATE ZWACHATSESSION SET ZFLAGS=256 WHERE Z_PK>$S;
UPDATE ZWAMESSAGE SET ZMESSAGESTATUS=8, ZDATAITEMVERSION=3,
       ZFLAGS=CASE ZISFROMME WHEN 1 THEN 16777280 ELSE 16777216 END,
       ZSENTDATE=ZMESSAGEDATE
 WHERE Z_PK>$M;
UPDATE ZWACHATSESSION SET ZLASTMESSAGE=(SELECT Z_PK FROM ZWAMESSAGE m WHERE m.ZCHATSESSION=ZWACHATSESSION.Z_PK ORDER BY m.ZSORT DESC LIMIT 1)
 WHERE ZLASTMESSAGE IS NULL AND EXISTS(SELECT 1 FROM ZWAMESSAGE m WHERE m.ZCHATSESSION=ZWACHATSESSION.Z_PK);
UPDATE ZWACHATSESSION SET ZLASTMESSAGEDATE=(SELECT ZMESSAGEDATE FROM ZWAMESSAGE WHERE Z_PK=ZWACHATSESSION.ZLASTMESSAGE)
 WHERE ZLASTMESSAGEDATE IS NULL AND ZLASTMESSAGE IS NOT NULL;
UPDATE ZWAGROUPMEMBER SET ZISACTIVE=1
 WHERE Z_PK>$G AND EXISTS(SELECT 1 FROM a.group_participants gp JOIN ZWACHATSESSION s ON s.Z_PK=ZWAGROUPMEMBER.ZCHATSESSION
                          WHERE gp.gjid=s.ZCONTACTJID AND gp.jid=ZWAGROUPMEMBER.ZMEMBERJID);
UPDATE ZWAMESSAGE SET ZSTARRED=1
 WHERE Z_PK>$M AND ZSTANZAID IN (SELECT key_id FROM a.starred_keys)
   AND EXISTS(SELECT 1 FROM a.starred_keys sk JOIN ZWACHATSESSION s ON s.Z_PK=ZWAMESSAGE.ZCHATSESSION
              WHERE sk.key_id=ZWAMESSAGE.ZSTANZAID AND sk.jid=s.ZCONTACTJID);
COMMIT;
DETACH a;
VACUUM;
SQL
